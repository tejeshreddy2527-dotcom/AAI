-- Run this in your Supabase SQL Editor (Dashboard -> SQL Editor -> New Query)

-- 1. Create the messages table
CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL,
    session_id TEXT DEFAULT 'default' NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('user', 'model')),
    content TEXT NOT NULL
);

-- 2. Create index on session_id and created_at for fast message retrieval
CREATE INDEX IF NOT EXISTS idx_messages_session ON messages (session_id, created_at ASC);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE messages ENABLE ROW LEVEL SECURITY;

-- 4. Allow public / anon read & write for this chatbot
CREATE POLICY "Allow anon insert and select on messages"
ON messages
FOR ALL
USING (true)
WITH CHECK (true);
