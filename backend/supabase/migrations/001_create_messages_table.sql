-- Stores all chat messages (user & model)
-- ============================================

CREATE TABLE IF NOT EXISTS messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL,
    session_id  TEXT NOT NULL DEFAULT 'default',
    role        TEXT NOT NULL CHECK (role IN ('user', 'model')),
    content     TEXT NOT NULL
);

-- Fast lookups by session, ordered by time
CREATE INDEX IF NOT EXISTS idx_messages_session
    ON messages (session_id, created_at ASC);

COMMENT ON TABLE messages IS 'Stores all chat messages between user and Gemini model';
COMMENT ON COLUMN messages.session_id IS 'Groups messages into separate conversations';
COMMENT ON COLUMN messages.role IS 'Either user or model (Gemini)';
