"""
Backend HTTP Server for Gemini Chatbot with Supabase integration.
Provides a REST API for the frontend and persists dialogue history into Supabase.
"""

import os
import json
import sys
import urllib.request
import urllib.error
from http.server import HTTPServer, BaseHTTPRequestHandler
from database import (
    save_message,
    get_messages,
    clear_messages,
    is_supabase_enabled,
    get_supabase_config
)

def load_env_file(filepath=".env"):
    """Load environment variables from .env if present."""
    paths = [
        filepath,
        os.path.join(os.path.dirname(__file__), filepath),
        os.path.join(os.path.dirname(__file__), "..", filepath)
    ]
    for p in paths:
        if os.path.exists(p):
            try:
                with open(p, "r", encoding="utf-8") as f:
                    for line in f:
                        line = line.strip()
                        if line and not line.startswith("#") and "=" in line:
                            key, val = line.split("=", 1)
                            key = key.strip()
                            val = val.strip().strip('"').strip("'")
                            if key and key not in os.environ:
                                os.environ[key] = val
                return
            except Exception:
                pass

load_env_file()

PORT = int(os.environ.get("PORT", 5000))
DEFAULT_MODEL = os.environ.get("GEMINI_MODEL", "gemini-2.5-flash")
CORS_ORIGIN = os.environ.get("CORS_ORIGIN", "*")
API_URL_TEMPLATE = "https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={api_key}"

def call_gemini_api(api_key, history, system_instruction=None, model=DEFAULT_MODEL):
    """Makes HTTP POST request to Google Gemini REST endpoint."""
    url = API_URL_TEMPLATE.format(model=model, api_key=api_key)
    payload = {"contents": history}
    if system_instruction:
        payload["systemInstruction"] = {"parts": [{"text": system_instruction}]}

    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(url, data=data, headers={"Content-Type": "application/json"})

    try:
        with urllib.request.urlopen(req, timeout=30) as response:
            result = json.loads(response.read().decode("utf-8"))
            candidates = result.get("candidates", [])
            if not candidates:
                return "No response generated by Gemini."
            parts = candidates[0].get("content", {}).get("parts", [])
            return "".join([p.get("text", "") for p in parts if "text" in p]).strip()
    except urllib.error.HTTPError as e:
        error_body = e.read().decode("utf-8")
        try:
            err_json = json.loads(error_body)
            err_msg = err_json.get("error", {}).get("message", error_body)
        except Exception:
            err_msg = error_body

        if e.code == 404 and model != "gemini-1.5-flash":
            return call_gemini_api(api_key, history, system_instruction, model="gemini-1.5-flash")

        raise RuntimeError(f"Gemini API ({e.code}): {err_msg}")
    except urllib.error.URLError as e:
        raise RuntimeError(f"Network Error: {e.reason}")

SYSTEM_PROMPT = "You are a friendly, helpful, and concise AI assistant powered by Gemini."

class ChatAPIHandler(BaseHTTPRequestHandler):
    def _send_cors_headers(self):
        self.send_header("Access-Control-Allow-Origin", CORS_ORIGIN)
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type")

    def do_OPTIONS(self):
        """Handle CORS preflight requests."""
        self.send_response(200)
        self._send_cors_headers()
        self.end_headers()

    def do_GET(self):
        """Handle GET requests: health check and chat history."""
        parsed_path = self.path.split("?")[0]

        if parsed_path in ("/", "/api/health"):
            self.send_response(200)
            self._send_cors_headers()
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            resp = {
                "status": "ok",
                "gemini_configured": bool(os.environ.get("GEMINI_API_KEY")),
                "supabase_connected": is_supabase_enabled()
            }
            self.wfile.write(json.dumps(resp).encode("utf-8"))
            return

        if parsed_path == "/api/history":
            session_id = "default"
            # Optional: parse ?session_id=... from query string
            if "?" in self.path:
                for param in self.path.split("?")[1].split("&"):
                    if param.startswith("session_id="):
                        session_id = param.split("=")[1]

            messages = get_messages(session_id=session_id)
            self.send_response(200)
            self._send_cors_headers()
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(json.dumps({"messages": messages}).encode("utf-8"))
            return

        self.send_response(404)
        self.end_headers()

    def do_POST(self):
        """Handle incoming messages or reset."""
        parsed_path = self.path.split("?")[0]

        if parsed_path == "/api/reset":
            session_id = "default"
            clear_messages(session_id=session_id)
            self.send_response(200)
            self._send_cors_headers()
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(json.dumps({"success": True, "message": "History cleared"}).encode("utf-8"))
            return

        if parsed_path == "/api/chat":
            api_key = os.environ.get("GEMINI_API_KEY", "").strip()
            if not api_key:
                self.send_response(400)
                self._send_cors_headers()
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                err = {"error": "GEMINI_API_KEY is missing on the server. Please add it to your .env file."}
                self.wfile.write(json.dumps(err).encode("utf-8"))
                return

            try:
                content_len = int(self.headers.get("Content-Length", 0))
                post_body = self.rfile.read(content_len).decode("utf-8")
                req_data = json.loads(post_body)
                user_message = req_data.get("message", "").strip()
                session_id = req_data.get("session_id", "default")

                if not user_message:
                    self.send_response(400)
                    self._send_cors_headers()
                    self.send_header("Content-Type", "application/json")
                    self.end_headers()
                    self.wfile.write(json.dumps({"error": "Empty message"}).encode("utf-8"))
                    return

                # 1. Persist user message to Supabase
                save_message(role="user", content=user_message, session_id=session_id)

                # 2. Fetch full conversation history from Supabase for Gemini context
                history_records = get_messages(session_id=session_id, limit=20)
                formatted_history = [
                    {"role": r["role"], "parts": [{"text": r["content"]}]}
                    for r in history_records
                ]

                # 3. Call Gemini
                bot_reply = call_gemini_api(api_key, formatted_history, system_instruction=SYSTEM_PROMPT)

                # 4. Persist Gemini reply to Supabase
                save_message(role="model", content=bot_reply, session_id=session_id)

                self.send_response(200)
                self._send_cors_headers()
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                self.wfile.write(json.dumps({
                    "reply": bot_reply,
                    "database": "supabase" if is_supabase_enabled() else "in-memory"
                }).encode("utf-8"))

            except Exception as e:
                self.send_response(500)
                self._send_cors_headers()
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                self.wfile.write(json.dumps({"error": str(e)}).encode("utf-8"))
        else:
            self.send_response(404)
            self.end_headers()

def run_server():
    server = HTTPServer(("0.0.0.0", PORT), ChatAPIHandler)
    print("\n" + "=" * 60)
    print(f"  Backend API Server running at http://localhost:{PORT}")
    print("=" * 60)

    # Status check
    api_key = os.environ.get("GEMINI_API_KEY")
    if api_key:
        print("  [+] Gemini API: Configured")
    else:
        print("  [!] Gemini API: NOT SET (Add GEMINI_API_KEY to .env)")

    if is_supabase_enabled():
        url, _ = get_supabase_config()
        print(f"  [+] Supabase DB: Connected ({url})")
    else:
        print("  [i] Supabase DB: Not configured (Using in-memory fallback)")
        print("      To persist chats, add SUPABASE_URL & SUPABASE_KEY to .env")

    print("=" * 60)
    print("Press Ctrl+C to stop.\n")

    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nStopping backend server...")
        server.server_close()

if __name__ == "__main__":
    run_server()
